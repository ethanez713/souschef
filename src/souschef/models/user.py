"""User accounts and the invites that create them.

The app is internet-facing, so account creation is closed: there is no public
registration form. The first account is claimed at first boot, and every account
after that needs a single-use invite generated by an existing user. That keeps
the attack surface to one login form no matter how many people end up using it.

Each user's kitchen is entirely their own -- pantry, recipes, plan, shopping
list, receipts. Only the ingredient catalog is shared, because it is reference
data about food rather than anything personal.
"""

from __future__ import annotations

from datetime import datetime

from sqlalchemy import ForeignKey, String
from sqlalchemy.orm import Mapped, mapped_column, relationship

from souschef.models.base import Base, TimestampMixin

# Long enough that guessing is hopeless, short enough to retype from a phone
# screen if the link doesn't survive being pasted into a chat.
INVITE_CODE_BYTES = 24


class User(Base, TimestampMixin):
    __tablename__ = "app_user"

    id: Mapped[int] = mapped_column(primary_key=True)

    # Stored casefolded so "Ethan" and "ethan" cannot become two accounts;
    # `display_name` keeps whatever capitalization was typed.
    username: Mapped[str] = mapped_column(String(64), unique=True, index=True)
    display_name: Mapped[str] = mapped_column(String(64))

    # argon2 hash. Kept out of __repr__ so it cannot land in a log line.
    password_hash: Mapped[str] = mapped_column(String(255))

    # Admins can issue invites and see the user list. The first account gets it.
    is_admin: Mapped[bool] = mapped_column(default=False)
    is_active: Mapped[bool] = mapped_column(default=True)

    last_login_at: Mapped[datetime | None] = mapped_column()

    # Bumped by a password change or a "sign out everywhere". Sessions carry the
    # value they were issued under, so raising it invalidates every existing
    # cookie -- without it, a stolen session survives the password reset meant
    # to kill it.
    session_epoch: Mapped[int] = mapped_column(default=0)

    def __repr__(self) -> str:
        return f"<User {self.id} {self.username!r}{' admin' if self.is_admin else ''}>"


class Invite(Base, TimestampMixin):
    """A single-use ticket to create one account.

    Only a hash of the code is stored. The code is 24 random bytes, so unlike a
    password it cannot be brute-forced from the hash and a fast digest is the
    right tool -- argon2 here would be cost with no benefit.
    """

    __tablename__ = "invite"

    id: Mapped[int] = mapped_column(primary_key=True)
    code_hash: Mapped[str] = mapped_column(String(64), unique=True, index=True)

    created_by_id: Mapped[int | None] = mapped_column(
        ForeignKey("app_user.id", ondelete="SET NULL"), index=True
    )
    expires_at: Mapped[datetime] = mapped_column()

    redeemed_at: Mapped[datetime | None] = mapped_column()
    redeemed_by_id: Mapped[int | None] = mapped_column(
        ForeignKey("app_user.id", ondelete="SET NULL")
    )

    note: Mapped[str | None] = mapped_column(String(120))  # "for Jordan"

    created_by: Mapped[User | None] = relationship(foreign_keys=[created_by_id])
    redeemed_by: Mapped[User | None] = relationship(foreign_keys=[redeemed_by_id])

    def __repr__(self) -> str:
        state = "redeemed" if self.redeemed_at else "open"
        return f"<Invite {self.id} {state}>"
